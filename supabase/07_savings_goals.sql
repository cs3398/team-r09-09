
-- 07: Savings Goals and Owl Points Tables

-- Stores savings goals for each user.
CREATE TABLE IF NOT EXISTS public.savings_goals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.user_profile(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    target_cents INTEGER NOT NULL CHECK (target_cents > 0),
    saved_cents INTEGER NOT NULL DEFAULT 0 CHECK (saved_cents >= 0 AND saved_cents <= target_cents),
    reward_awarded BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Stores individual contributions toward savings goals.
CREATE TABLE IF NOT EXISTS public.savings_contributions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id INTEGER NOT NULL REFERENCES public.savings_goals(id) ON DELETE CASCADE,
    amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Stores each user's Owl Points balance.
CREATE TABLE IF NOT EXISTS public.owl_points (
    user_id INTEGER PRIMARY KEY REFERENCES public.user_profile(id) ON DELETE CASCADE,
    balance INTEGER NOT NULL DEFAULT 150 CHECK (balance >= 0)
);


-- Stores vouchers redeemed using Owl Points.
-- Each user can redeem a specific voucher only once.
CREATE TABLE IF NOT EXISTS public.redeemed_vouchers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.user_profile(id) ON DELETE CASCADE,
    coupon_id TEXT NOT NULL,
    voucher_code TEXT NOT NULL UNIQUE,
    points_spent INTEGER NOT NULL CHECK (points_spent > 0),
    redeemed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, coupon_id)
);
