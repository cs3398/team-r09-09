--08: Financial Profiles Table
CREATE TABLE public.financial_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE
        REFERENCES public.user_profile(id) ON DELETE CASCADE,

    monthly_income INTEGER NOT NULL DEFAULT 0
        CHECK (monthly_income >= 0),
    housing_expenses INTEGER NOT NULL DEFAULT 0
        CHECK (housing_expenses >= 0),
    food_expenses INTEGER NOT NULL DEFAULT 0
        CHECK (food_expenses >= 0),
    transportation_expenses INTEGER NOT NULL DEFAULT 0
        CHECK (transportation_expenses >= 0),
    other_expenses INTEGER NOT NULL DEFAULT 0
        CHECK (other_expenses >= 0)
);